export const DICTS: Record<Lang, Dict> = { uz, ru };
export type TKey = keyof typeof uz;

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s = (DICTS[lang] ?? uz)[key] ?? uz[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function asLang(v: unknown): Lang {
  return v === "ru" ? "ru" : "uz";
}

/** Server: language of the request (header set by the Mini App). */
export function reqLang(req: Request): Lang {
  return asLang(req.headers.get("x-lang"));
}

export function moneyIn(lang: Lang, n: number): string {
  const s = String(Math.round(n || 0)).replace(/\B(?=(\d{3})+(?!\d))/g, " ");
  return `${s} ${DICTS[lang].sum}`;
}

const MONTHS: Record<Lang, string[]> = {
  uz: ["yanvar", "fevral", "mart", "aprel", "may", "iyun", "iyul", "avgust", "sentabr", "oktabr", "noyabr", "dekabr"],
  ru: ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"],
};
const WEEKDAYS: Record<Lang, string[]> = {
  uz: ["Yak", "Dush", "Sesh", "Chor", "Pay", "Jum", "Shan"],
  ru: ["Вс", "Пн", "Вт", "Ср", "Чт", "Пт", "Сб"],
};

export function dayLabel(lang: Lang, d: Date): { top: string; bottom: string; full: string } {
  const month = MONTHS[lang][d.getMonth()];
  return { top: WEEKDAYS[lang][d.getDay()], bottom: String(d.getDate()), full: `${d.getDate()}-${month}`.replace("-", lang === "ru" ? " " : "-") };
}

export function dateTimeIn(lang: Lang, iso?: string): string {
  if (!iso) return "";
  const d = new Date(iso);
  const m = MONTHS[lang][d.getMonth()].slice(0, lang === "ru" ? 3 : 3);
  return `${d.getDate()} ${m}, ${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`;
}

/** Picks the Russian field when it exists, otherwise the Uzbek one. */
export function loc<T extends Record<string, unknown>>(lang: Lang, row: T, field: string): string {
  const ru = row[`${field}_ru`];
  if (lang === "ru" && typeof ru === "string" && ru.trim()) return ru;
  return String(row[field] ?? "");
}
